#!/usr/bin/env python3
"""Generate docs/catalogue.md: what each profile installs and what each hook
writes on its own.

    build_catalogue.py            render and write docs/catalogue.md
    build_catalogue.py --check    exit 1 if the file is stale or missing
    --path <file>                 use <file> instead of <repo>/docs/catalogue.md
    --repo <dir>                  read registry, manifests, skills, agents and
                                  install.sh from <dir> (tests; Python modules
                                  always load from this script's own repo)

Exit 2 on any input problem (nothing written). Stdlib only.
"""
import argparse
import glob
import importlib.util
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

# tools/catalogue/build_catalogue.py -> tools/catalogue -> tools -> repo root
REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.realpath(__file__))))
sys.path.insert(0, os.path.join(REPO, "lib"))
import hook_manifest  # noqa: E402
import profiles  # noqa: E402


def _load_by_path(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


setup_config = _load_by_path("setup_config", os.path.join(REPO, "lib", "setup_config.py"))

STALE = ("docs/catalogue.md is stale — run python3 tools/catalogue/build_catalogue.py "
         "and commit the result")

HEADER = (
    "<!-- Generated by tools/catalogue/build_catalogue.py — do not edit by hand. "
    "Re-run it and commit the result; local CI fails when this file is stale. -->\n"
    "# Toolkit catalogue\n"
    "\n"
    "What each profile installs. A profile is one plugin in the `claude-code-toolkit` marketplace. "
    "Choose them with\n"
    "`\"profiles\"` in `~/.config/claude-code-toolkit/config.json` (keep `\"continuity\"` "
    "in the list), then run\n"
    "`./install.sh` in the primary checkout. With no `\"profiles\"` key you get core and "
    "continuity.\n"
)


def writer_problems(writers, relpaths):
    """Sorted problems: a hook with no writers entry, an entry matching no hook."""
    keys = {k for k in writers if not k.startswith("//")}
    problems = ["no writers entry for %s" % r for r in set(relpaths) - keys]
    problems += ["writers entry for %s matches no hook" % k for k in keys - set(relpaths)]
    return sorted(problems)


def cli_rows(repo):
    """[(command name, source path relative to the repo)] from install.sh --manifest.

    Runs under a throwaway HOME with no config so the output is the same on
    every machine; raises RuntimeError when the manifest cannot be read.
    """
    sandbox = tempfile.mkdtemp()
    try:
        env = dict(os.environ)
        env["HOME"] = sandbox
        env["USERPROFILE"] = sandbox
        env["CLAUDE_TOOLKIT_CONFIG"] = os.path.join(sandbox, "no-such-config.json")
        for key in [k for k in env if k.startswith("GIT_")]:
            del env[key]  # install.sh runs git; an inherited GIT_DIR would misdirect it
        try:
            result = subprocess.run(["bash", os.path.join(repo, "install.sh"), "--manifest"],
                                    cwd=repo, env=env, stdin=subprocess.DEVNULL,
                                    capture_output=True, text=True, encoding="utf-8")
        except OSError as exc:
            raise RuntimeError("cannot run install.sh --manifest: %s" % exc)
    finally:
        shutil.rmtree(sandbox, ignore_errors=True)
    if result.returncode != 0:
        raise RuntimeError("install.sh --manifest exited %d: %s"
                           % (result.returncode, result.stderr.strip()[-300:]))
    root = os.path.realpath(repo)
    rows = []
    for line in result.stdout.splitlines():
        if not line.startswith("link\t"):
            continue
        parts = line.split("\t")
        if len(parts) < 3:
            continue
        source = os.path.relpath(os.path.realpath(parts[1]), root).replace(os.sep, "/")
        rows.append((os.path.basename(parts[2]), source))
    if not rows:
        raise RuntimeError("install.sh --manifest yielded no link rows")
    return rows


def _cell(text):
    return str(text).replace("|", "\\|").replace("\r", " ").replace("\n", " ")


def _table(headers, rows):
    lines = ["| " + " | ".join(headers) + " |",
             "| " + " | ".join("---" for _ in headers) + " |"]
    lines += ["| " + " | ".join(_cell(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def _tool_explanations():
    return {tool["name"]: tool["explanation"]
            for group in setup_config.TOOL_CATALOGUE for tool in group["tools"]}


def _event(row):
    return "%s (%s)" % (row["event"], row["matcher"]) if row["matcher"] else row["event"]


def _hook_rows(registrations, writers, explanations):
    grouped = {}  # relpath -> [events], insertion order = first appearance
    for row in registrations:
        events = grouped.setdefault(row["relpath"], [])
        if _event(row) not in events:
            events.append(_event(row))
    out = []
    for relpath, events in grouped.items():
        parts = relpath.split("/")
        tool = parts[1] if len(parts) > 1 and parts[0] == "tools" else None
        out.append(("`%s`" % os.path.basename(relpath), ", ".join(events),
                    writers[relpath], explanations.get(tool, "—")))
    return out


def front_matter_description(path):
    """The `description:` value of a markdown file's `---` front matter.

    Block scalars (`>` or `|`, with optional `-`/`+`) are joined from their
    indented lines with single spaces; quoted inline values are unquoted.
    Returns "" when there is no front matter or no description.
    """
    with open(path, encoding="utf-8") as handle:
        lines = handle.read().splitlines()
    if not lines or lines[0].strip() != "---":
        return ""
    block = []
    for line in lines[1:]:
        if line.strip() == "---":
            break
        block.append(line)
    for index, line in enumerate(block):
        if not line.startswith("description:"):
            continue
        value = line[len("description:"):].strip()
        if re.fullmatch(r"[>|][+-]?", value):
            parts = []
            for follow in block[index + 1:]:
                if follow.strip() and not follow[0].isspace():
                    break
                if follow.strip():
                    parts.append(follow.strip())
            return " ".join(parts)
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        return value
    return ""


def first_sentence(text):
    """Text up to the first `.`, `!` or `?` followed by whitespace or the end."""
    match = re.search(r"[.!?](?=\s|$)", text)
    return text[:match.end()] if match else text


def _description(path):
    return first_sentence(front_matter_description(path))


def skill_plugin_rows(repo):
    """[(plugin name, install command, first sentence)] for ./plugins/ marketplace entries."""
    try:
        with open(os.path.join(repo, ".claude-plugin", "marketplace.json"),
                  encoding="utf-8") as handle:
            market = json.load(handle)
    except (OSError, ValueError) as exc:
        raise RuntimeError("cannot read .claude-plugin/marketplace.json: %s" % exc)
    rows = []
    for entry in sorted(market.get("plugins", []), key=lambda e: e["name"]):
        source = entry.get("source", "")
        if not source.startswith("./plugins/"):
            continue
        skills = glob.glob(os.path.join(repo, source[2:], "skills", "*", "SKILL.md"))
        if len(skills) != 1:
            raise RuntimeError("%s: expected exactly one SKILL.md, found %d"
                               % (entry["name"], len(skills)))
        rows.append((entry["name"],
                     "claude plugin install %s@%s" % (entry["name"], market["name"]),
                     _description(skills[0])))
    return rows


def _inputs(repo):
    """(registry, registrations, writers); raises RuntimeError on a bad input."""
    try:
        registry = profiles.load_registry(repo)
        registrations = hook_manifest.plugin_registrations(repo)
        with open(os.path.join(repo, "claude", "profiles.json"), encoding="utf-8") as handle:
            writers = json.load(handle).get("writers")
    except (profiles.RegistryError, hook_manifest.ManifestError, OSError, ValueError) as exc:
        raise RuntimeError(str(exc))
    if not isinstance(writers, dict):
        raise RuntimeError("claude/profiles.json: `writers` must be an object")
    return registry, registrations, writers


def _skill_plugin_dependencies(repo, entry, registry):
    """A profile plugin's manifest dependencies that are not profile plugins:
    the skill plugins the CLI installs alongside it. Raises RuntimeError on an
    unreadable manifest."""
    path = os.path.join(repo, entry["dir"], ".claude-plugin", "plugin.json")
    try:
        with open(path, encoding="utf-8") as handle:
            deps = json.load(handle).get("dependencies", [])
    except (OSError, ValueError) as exc:
        raise RuntimeError("%s: %s" % (path, exc))
    profile_plugins = {e["plugin"] for e in registry.values()}
    return sorted(d for d in deps if isinstance(d, str) and d not in profile_plugins)


def render(repo, inputs=None, rows=None):
    registry, registrations, writers = inputs or _inputs(repo)
    explanations = _tool_explanations()
    out = [HEADER]
    for name, entry in registry.items():
        out.append("## %s — `%s`\n" % (name, entry["plugin"]))
        if name == "core":
            tag = "Always installed."
        elif entry["default"]:
            tag = "Installed by default."
        else:
            tag = "Optional."
        line = "%s %s" % (entry["summary"], tag)
        extra = [r for r in entry["requires"] if r != "core"]
        if extra:
            line += " Also brings: %s." % ", ".join(extra)
        skill_deps = _skill_plugin_dependencies(repo, entry, registry)
        if skill_deps:
            line += " Also installs: %s." % ", ".join("`%s`" % d for d in skill_deps)
        out.append(line + "\n")

        skills = sorted(glob.glob(os.path.join(repo, "skills", name, "*", "SKILL.md")),
                        key=lambda p: os.path.basename(os.path.dirname(p)))
        if skills:
            table = _table(["Command", "What it does"],
                           [("`/%s`" % os.path.basename(os.path.dirname(p)), _description(p))
                            for p in skills])
            out.append("### Commands\n\n" + table + "\n")
        if entry["agents"]:
            agents = sorted(glob.glob(os.path.join(repo, "agents", "*.md")))
            table = _table(["Agent", "What it does"],
                           [("`%s:%s`" % (entry["plugin"], os.path.basename(p)[:-3]),
                             _description(p)) for p in agents])
            out.append("### Agents\n\n" + table + "\n")
        mine = [r for r in registrations if r["profile"] == name]
        if mine:
            table = _table(["Hook", "Runs on", "Writes on its own", "What it is for"],
                           _hook_rows(mine, writers, explanations))
            out.append("### Hooks\n\n" + table + "\n")

    plugin_rows = skill_plugin_rows(repo)
    if plugin_rows:
        table = _table(["Plugin", "Install", "What it does"],
                       [("`%s`" % n, "`%s`" % i, d) for n, i, d in plugin_rows])
        out.append("## Skill plugins — optional, one skill each\n\n"
                   "Install any of these on its own; none adds hooks or commands.\n\n"
                   + table + "\n")

    if rows is None:
        rows = cli_rows(repo)
    table = _table(["Command", "Source"],
                   [("`%s`" % name, "`%s`" % source) for name, source in rows])
    out.append("## Commands on your PATH — every profile\n\n"
               "`./install.sh` links these into `~/.local/bin` whatever profiles you choose.\n\n"
               + table + "\n")
    return "\n".join(out)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--path")
    parser.add_argument("--repo")
    args = parser.parse_args(argv)
    repo = os.path.realpath(args.repo) if args.repo else REPO
    path = args.path or os.path.join(repo, "docs", "catalogue.md")

    # Writers check first: a gap exits before install.sh ever runs.
    try:
        inputs = _inputs(repo)
    except RuntimeError as exc:
        print(exc, file=sys.stderr)
        return 2
    problems = writer_problems(inputs[2], {r["relpath"] for r in inputs[1]})
    if problems:
        for problem in problems:
            print(problem, file=sys.stderr)
        return 2
    try:
        text = render(repo, inputs)
    except RuntimeError as exc:
        print(exc, file=sys.stderr)
        return 2

    if args.check:
        try:
            with open(path, "rb") as handle:
                current = handle.read()
        except OSError:
            current = None
        if current == text.encode("utf-8"):
            return 0
        print(STALE, file=sys.stderr)
        return 1
    with open(path, "w", encoding="utf-8", newline="") as handle:
        handle.write(text)
    print("wrote docs/catalogue.md")
    return 0


if __name__ == "__main__":
    for _stream in (sys.stdout, sys.stderr):
        try:
            _stream.reconfigure(encoding="utf-8", errors=_stream.errors)
        except (AttributeError, ValueError):
            pass
    sys.exit(main())
